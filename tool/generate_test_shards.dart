import 'dart:convert';
import 'dart:io';

/// Regenerates `tool/test_shards.json`, the balanced file-level shard plan.
///
/// CI used to shard with `flutter test --total-shards 4 --shard-index N`.
/// That partitions by *test case*, so every shard still loaded and compiled
/// almost the entire suite: the four shards together did several times the
/// compile work of a single full-suite run. Sharding by *file* instead lets
/// each job compile only the files it runs.
///
/// The plan is balanced by longest-processing-time-first (LPT) over the
/// measured per-file costs in `tool/test_shard_weights.json`. File size and
/// case count were measured and rejected: neither reproduces the tight spread
/// that real weights do. A file missing from the weight map falls back to the
/// map's median so a newly added test is never dropped from the plan.
///
/// `test/guards/test_shard_plan_guard_test.dart` fails while the committed
/// plan and weights disagree with the test tree on disk.
///
/// Usage:
///   dart run tool/generate_test_shards.dart
///   dart run tool/generate_test_shards.dart --shards 6
///   dart run tool/generate_test_shards.dart --from-report report.json
void main(List<String> args) {
  final int shardCount = _intOption(args, '--shards') ?? 4;
  final String? report = _stringOption(args, '--from-report');

  final File weightsFile = File(
    '${Directory.current.path}/tool/test_shard_weights.json',
  );
  final Map<String, dynamic> weights = weightsFile.existsSync()
      ? jsonDecode(weightsFile.readAsStringSync()) as Map<String, dynamic>
      : <String, dynamic>{};

  final Map<String, int> measured = report == null
      ? _storedWeights(weights)
      : _weightsFromReport(File('${Directory.current.path}/$report'));
  if (report != null) {
    if (measured.isEmpty) {
      // Fail closed. Writing an empty map over the committed weights would
      // make the next plan a silent placeholder, and a placeholder plan still
      // runs every file, so nothing downstream would go red.
      stderr.writeln('No per-file weights parsed from $report; not writing.');
      exitCode = 1;
      return;
    }
    weights['weights'] = measured;
  }

  // A test file with no measurement still has to go somewhere, and leaving it
  // unweighted would make the plan disagree with the weight map. Backfill the
  // median so the two always describe the same set of files; the placeholder is
  // a balancing approximation, never a reason to leave a file out of a shard.
  weights['default_ms'] ??= _median(measured);
  final int fallback = weights['default_ms'] as int;
  final _TestTree tree = _readTestTree();
  if (tree.planned.isEmpty) {
    stderr.writeln('No test files to plan; refusing to write an empty plan.');
    exitCode = 1;
    return;
  }
  final List<String> backfilled = <String>[
    for (final String path in tree.planned)
      if (!measured.containsKey(path)) path,
  ];
  for (final String path in backfilled) {
    measured[path] = fallback;
  }
  // Keep the in-memory view and the file describing exactly the same map.
  weights['weights'] = measured;

  final List<List<_File>> groups = _balance(
    tree.planned.map((String path) => _File(path, measured[path]!)).toList(),
    shardCount,
  );

  final Map<String, dynamic> plan = <String, dynamic>{
    'note':
        'Generated by `dart run tool/generate_test_shards.dart`. Each entry is '
        'one CI test job and is consumed as a GitHub Actions matrix through '
        '`fromJSON`. Do not hand-edit: run the generator and commit the result.',
    'count': groups.length,
    'browser': tree.browser,
    'include': <Map<String, dynamic>>[
      for (int i = 0; i < groups.length; i++)
        <String, dynamic>{
          'index': i,
          'weight_ms': groups[i].fold<int>(0, (int a, _File f) => a + f.cost),
          'files': groups[i].map((_File f) => f.path).toList(),
        },
    ],
  };

  final File planFile = File('${Directory.current.path}/tool/test_shards.json');
  planFile.parent.createSync(recursive: true);
  planFile.writeAsStringSync(
    '${const JsonEncoder.withIndent('  ').convert(plan)}\n',
  );

  // The weights file is rewritten whenever it changes, so a backfilled
  // placeholder is committed alongside the plan that depends on it.
  if (report != null || backfilled.isNotEmpty) {
    weights['measured'] = DateTime.now().toIso8601String().substring(0, 10);
  }
  final String weightsJson =
      '${const JsonEncoder.withIndent('  ').convert(weights)}\n';
  if (report != null || backfilled.isNotEmpty) {
    weightsFile.writeAsStringSync(weightsJson);
  }

  final List<int> costs = (plan['include'] as List<dynamic>)
      .map((dynamic e) => (e as Map<String, dynamic>)['weight_ms'] as int)
      .toList();
  final int low = costs.reduce((int a, int b) => a < b ? a : b);
  final int high = costs.reduce((int a, int b) => a > b ? a : b);
  stdout.writeln(
    'Wrote ${groups.length} groups covering ${tree.planned.length} test files '
    '(+${tree.browser.length} browser) to tool/test_shards.json; '
    'per-group weight ${(low / 1000).toStringAsFixed(1)}-'
    '${(high / 1000).toStringAsFixed(1)}s '
    '(spread ${((high - low) / high * 100).toStringAsFixed(1)}%).',
  );
}

/// A test file and its measured cost in milliseconds.
class _File {
  _File(this.path, this.cost);

  /// Repository-relative path, as passed to `flutter test`.
  final String path;

  /// Measured cost used for balancing.
  final int cost;
}

/// The test tree on disk, split into planned files and browser-tagged files.
class _TestTree {
  _TestTree(this.planned, this.browser);

  /// Files that run under `flutter test` and therefore belong to a shard.
  final List<String> planned;

  /// Files tagged `@TestOn('browser')`, which a plain `flutter test` skips.
  final List<String> browser;
}

/// Reads the stored weight map, keyed by repository-relative test path.
Map<String, int> _storedWeights(Map<String, dynamic> weights) {
  final Map<String, dynamic> raw =
      weights['weights'] as Map<String, dynamic>? ?? <String, dynamic>{};
  return raw.map((String k, dynamic v) => MapEntry<String, int>(k, v as int));
}

/// Derives per-file costs from a `flutter test --reporter json` report.
///
/// A suite's cost is its span: from its first `testStart` to its last
/// `testDone`. That includes the compile the suite pays for, which is the
/// dominant term, and it is the quantity the shard plan needs to balance.
Map<String, int> _weightsFromReport(File report) {
  if (!report.existsSync()) {
    stderr.writeln('Report not found: ${report.path}');
    exitCode = 1;
    return <String, int>{};
  }

  final Map<String, String> suitePathById = <String, String>{};
  final Map<String, String> suiteOfTest = <String, String>{};
  final Map<String, int> firstStart = <String, int>{};
  final Map<String, int> lastEnd = <String, int>{};

  for (final String line in report.readAsLinesSync()) {
    if (line.trim().isEmpty) {
      continue;
    }
    final Map<String, dynamic> event = jsonDecode(line) as Map<String, dynamic>;
    final int time = (event['time'] as num?)?.toInt() ?? 0;

    switch (event['type']) {
      case 'suite':
        final Map<String, dynamic> suite =
            event['suite'] as Map<String, dynamic>;
        suitePathById['${suite['id']}'] = _relative(suite['path'] as String);
      case 'testStart':
        final Map<String, dynamic> test = event['test'] as Map<String, dynamic>;
        final String suiteId = '${test['suiteID']}';
        suiteOfTest['${test['id']}'] = suiteId;
        if (!firstStart.containsKey(suiteId)) {
          firstStart[suiteId] = time;
        }
      case 'testDone':
        final String suiteId = suiteOfTest['${event['testID']}'] ?? '';
        if (suiteId.isEmpty) {
          continue;
        }
        // Every test's end time is recorded; the suite's span is closed below
        // by taking the latest one for each suite.
        if (lastEnd[suiteId] == null || time > lastEnd[suiteId]!) {
          lastEnd[suiteId] = time;
        }
    }
  }

  final Map<String, int> measured = <String, int>{};
  for (final MapEntry<String, int> entry in firstStart.entries) {
    final String? path = suitePathById[entry.key];
    if (path == null) {
      continue;
    }
    measured[path] = (lastEnd[entry.key] ?? entry.value) - entry.value;
  }
  return measured;
}

/// Converts any absolute or repository-rooted path to `test/...` form.
String _relative(String path) {
  final int marker = path.indexOf('/test/');
  if (marker >= 0) {
    return path.substring(marker + 1);
  }
  return path.replaceFirst(RegExp(r'^\.?/'), '');
}

/// Walks `test/` and partitions `*_test.dart` files by their `@TestOn` tag.
_TestTree _readTestTree() {
  final Directory root = Directory('${Directory.current.path}/test');
  final List<String> planned = <String>[];
  final List<String> browser = <String>[];

  for (final FileSystemEntity entity in root.listSync(recursive: true)) {
    if (entity is! File || !entity.path.endsWith('_test.dart')) {
      continue;
    }
    final String path = _relative(entity.path);
    if (RegExp(r"@TestOn\(\s*'browser'").hasMatch(entity.readAsStringSync())) {
      browser.add(path);
    } else {
      planned.add(path);
    }
  }

  planned.sort();
  browser.sort();
  return _TestTree(planned, browser);
}

/// Greedily assigns files to the least-loaded group, longest first.
///
/// LPT is the standard 4/3-approximation for makespan minimisation on
/// identical machines and is within a few percent of optimal on this suite's
/// weights.
List<List<_File>> _balance(List<_File> files, int groups) {
  final List<_File> ordered = <_File>[...files]
    ..sort((_File a, _File b) => b.cost.compareTo(a.cost));
  final int count = groups.clamp(1, ordered.length);

  final List<List<_File>> buckets = List<List<_File>>.generate(
    count,
    (_) => <_File>[],
  );
  final List<int> loads = List<int>.filled(count, 0);

  for (final _File file in ordered) {
    int target = 0;
    for (int i = 1; i < count; i++) {
      if (loads[i] < loads[target]) {
        target = i;
      }
    }
    buckets[target].add(file);
    loads[target] += file.cost;
  }

  for (final List<_File> bucket in buckets) {
    bucket.sort((_File a, _File b) => a.path.compareTo(b.path));
  }

  // Emitting the heaviest group first keeps the reported per-group weights
  // monotonic, which makes a diff of the plan readable.
  final List<int> order = List<int>.generate(count, (int i) => i)
    ..sort((int a, int b) => loads[b].compareTo(loads[a]));
  return <List<_File>>[for (final int i in order) buckets[i]];
}

/// Returns the median of the measured costs, used for unlisted files.
int _median(Map<String, int> weights) {
  if (weights.isEmpty) {
    return 1000;
  }
  final List<int> values = weights.values.toList()..sort();
  return values[values.length ~/ 2];
}

/// Reads `--name value` from the argument list, if present.
String? _stringOption(List<String> args, String name) {
  final int index = args.indexOf(name);
  if (index < 0 || index + 1 >= args.length) {
    return null;
  }
  return args[index + 1];
}

/// Reads `--name value` from the argument list as an integer, if present.
int? _intOption(List<String> args, String name) {
  final String? value = _stringOption(args, name);
  return value == null ? null : int.tryParse(value);
}
